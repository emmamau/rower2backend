const fs = require('fs');
const path = require('path');

const targetPath = path.resolve(__dirname, '../src/environments/environment.prod.ts');
let rawApiUrl = process.env.API_URL || process.env.RENDER_EXTERNAL_URL || process.env.BACKEND_URL || 'https://rower-api-service.onrender.com';

rawApiUrl = rawApiUrl.trim();

// If Render passed the internal service name (which browsers cannot resolve) or empty, use the exact public domain
if (!rawApiUrl || rawApiUrl === 'rower-api-service' || rawApiUrl === 'https://rower-api-service' || rawApiUrl === 'http://rower-api-service') {
  rawApiUrl = 'https://rower-api-service.onrender.com';
} else {
  if (!rawApiUrl.startsWith('http://') && !rawApiUrl.startsWith('https://')) {
    rawApiUrl = `https://${rawApiUrl}`;
  }
}

const apiUrl = rawApiUrl.replace(/\/$/, '');
console.log(`[set-env] Inlining final public API_URL into Angular environment: "${apiUrl}"`);

const envFileContent = `// Auto-generated by scripts/set-env.js during Render build
export const environment = {
  production: true,
  apiUrl: '${apiUrl}'
};
`;

fs.writeFileSync(targetPath, envFileContent, { encoding: 'utf8' });
console.log(`[set-env] Successfully wrote environment config to ${targetPath}`);
